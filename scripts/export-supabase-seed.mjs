function upsert(table, columns, rows) {
  if (rows.length === 0) return "";
  const assignments = columns
    .filter((column) => column !== "id")
    .map((column) => `${column} = excluded.${column}`)
    .join(", ");
  return [
    `insert into public.${table} (${columns.join(", ")})`,
    "values",
    rows.map((row) => `  (${row.map(sqlValue).join(", ")})`).join(",\n"),
    `on conflict (id) do update set ${assignments};`
  ].join("\n");
}

function sqlValue(value) {
  if (value === null || value === undefined) return "null";
  if (typeof value === "boolean") return value ? "true" : "false";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "null";
  if (typeof value === "object" && value.kind === "pg-array") return `array[${value.values.map(sqlString).join(", ")}]::text[]`;
  return sqlString(String(value));
}

function sqlString(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

function pgArray(values) {
  return { kind: "pg-array", values };
}
